export function buildTextStyleFromPreset(preset: TextPreset, textOverride?: string): TextStyleState {
  return {
    ...createDefaultTextStyle(textOverride ?? preset.sampleText),
    ...preset.style,
    text: textOverride ?? preset.sampleText,
  };
}
